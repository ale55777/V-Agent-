"""Load each real model and measure it on this machine. Prints a benchmark and writes JSON.

Speech recognition is tested on audio generated by the TTS engine itself, so no sample
needs to be bundled. Exits non-zero if any stage fails.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.config.settings import get_settings  # noqa: E402
from app.services.asr.whisper import WhisperRecognizer  # noqa: E402
from app.services.llm.ollama import OllamaClient, SentenceChunker, build_messages  # noqa: E402
from app.services.tts.engines import KokoroEngine, PiperEngine  # noqa: E402
from app.services.vad.silero import SileroVAD  # noqa: E402

SENTENCE = "The quick brown fox jumps over the lazy dog near the river bank."


def resample(samples: np.ndarray, source: int, target: int = 16000) -> np.ndarray:
    positions = np.linspace(0, len(samples) - 1, int(len(samples) * target / source))
    return np.interp(positions, np.arange(len(samples)), samples).astype(np.float32)


def bench_tts(engine, results: dict) -> np.ndarray:
    started = time.perf_counter()
    audio = np.concatenate(list(engine.synthesize(SENTENCE, None)))
    elapsed = time.perf_counter() - started
    seconds = len(audio) / engine.sample_rate
    results[engine.name] = {
        "synth_seconds": round(elapsed, 3),
        "audio_seconds": round(seconds, 3),
        "real_time_factor": round(elapsed / seconds, 3),
    }
    print(f"  {engine.name}: {elapsed:.2f}s for {seconds:.2f}s of audio (RTF {elapsed / seconds:.2f})")
    return resample(audio, engine.sample_rate)


def bench_vad(path: Path, speech: np.ndarray, results: dict) -> None:
    vad = SileroVAD(path)
    silence_probs = [vad.probability(np.zeros(512, dtype=np.float32)) for _ in range(30)]
    vad.reset()
    speech_probs = []
    started = time.perf_counter()
    for start in range(0, len(speech) - 512, 512):
        speech_probs.append(vad.probability(speech[start : start + 512]))
    per_frame_ms = (time.perf_counter() - started) / max(1, len(speech_probs)) * 1000
    results["vad"] = {
        "per_frame_ms": round(per_frame_ms, 3),
        "max_on_silence": round(max(silence_probs), 3),
        "max_on_speech": round(max(speech_probs), 3),
    }
    print(f"  {per_frame_ms:.2f} ms/frame; silence max {max(silence_probs):.3f}, speech max {max(speech_probs):.3f}")
    assert max(speech_probs) > 0.5 > max(silence_probs), "VAD did not separate speech from silence"


def bench_stt(settings, speech: np.ndarray, results: dict) -> None:
    started = time.perf_counter()
    recognizer = WhisperRecognizer(
        settings.stt_model, settings.models_dir, settings.stt_compute_type, settings.stt_threads
    )
    load = time.perf_counter() - started
    recognizer.transcribe(np.zeros(8000, dtype=np.float32), "en", True)
    started = time.perf_counter()
    transcript = recognizer.transcribe(speech, "en", True)
    elapsed = time.perf_counter() - started
    results["stt"] = {
        "model": recognizer.name,
        "load_seconds": round(load, 2),
        "transcribe_seconds": round(elapsed, 3),
        "audio_seconds": round(len(speech) / 16000, 2),
        "text": transcript.text,
    }
    print(f"  loaded in {load:.1f}s; {elapsed:.2f}s for {len(speech) / 16000:.1f}s of audio")
    print(f"  heard: {transcript.text!r}")
    assert "fox" in transcript.text.lower() or "dog" in transcript.text.lower(), "transcript looks wrong"


async def bench_llm(settings, results: dict, prompts: list[str]) -> None:
    client = OllamaClient(settings)
    started = time.perf_counter()
    await client.warm_up()
    print(f"  model load {time.perf_counter() - started:.1f}s")
    results["llm"] = {"model": settings.llm_model, "load_seconds": round(time.perf_counter() - started, 2), "turns": []}
    for prompt in prompts:
        messages = build_messages([{"role": "user", "content": prompt}], "", "en", settings.llm_num_ctx, settings.llm_num_predict)
        chunker = SentenceChunker()
        started = time.perf_counter()
        first_token = first_piece = None
        text, tokens = "", 0
        async for token in client.stream(messages):
            first_token = first_token or time.perf_counter() - started
            text += token
            tokens += 1
            if first_piece is None and chunker.push(token):
                first_piece = time.perf_counter() - started
        total = time.perf_counter() - started
        first_piece = first_piece or total
        results["llm"]["turns"].append({
            "prompt": prompt, "reply": text.strip(), "first_token_s": round(first_token or 0, 3),
            "first_speakable_piece_s": round(first_piece, 3), "total_s": round(total, 3),
            "tokens_per_s": round(tokens / total, 1),
        })
        print(f"  first token {first_token:.2f}s, first speakable piece {first_piece:.2f}s, "
              f"{tokens / total:.1f} tok/s\n    Q: {prompt}\n    A: {text.strip()}")
    await client.close()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    parser.add_argument("--skip-llm", action="store_true")
    args = parser.parse_args()
    settings = get_settings()
    results: dict = {"tts": {}}

    print("Text to speech")
    speech = None
    for label, factory in (
        ("piper", lambda: PiperEngine(settings.models_dir, settings.piper_voice, settings.tts_threads)),
        ("kokoro", lambda: KokoroEngine(settings.models_dir, settings.tts_threads, settings.kokoro_voice)),
    ):
        started = time.perf_counter()
        engine = factory()
        print(f"  {label} loaded in {time.perf_counter() - started:.1f}s, {len(engine.voices())} voices")
        bench_tts(engine, results["tts"])  # first run includes allocation, so measure the second
        audio = bench_tts(engine, results["tts"])
        if speech is None or label == "kokoro":
            speech = audio
        del engine

    print("Silero VAD")
    bench_vad(settings.models_dir / "silero" / "silero_vad.onnx", speech, results)
    print("Speech recognition")
    bench_stt(settings, speech, results)
    if not args.skip_llm:
        print(f"LLM ({settings.llm_model})")
        asyncio.run(bench_llm(settings, results, ["What is the capital of France?", "Explain gravity to a child."]))

    if args.output:
        args.output.write_text(json.dumps(results, indent=2))
    print("All model checks passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
